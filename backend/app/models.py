from sqlalchemy import (
    Column,
    Integer,
    String,
    Text,
    ForeignKey
)

from sqlalchemy.orm import relationship

from app.database import Base


# =========================================================
# USER
# =========================================================

class User(Base):

    __tablename__ = "users"

    id = Column(
        Integer,
        primary_key=True,
        index=True
    )

    name = Column(
        String(100),
        nullable=False
    )

    email = Column(
        String(150),
        unique=True,
        index=True,
        nullable=False
    )

    password_hash = Column(
        String(255),
        nullable=False
    )

    # -----------------------------------------------------
    # RELATIONSHIP
    # -----------------------------------------------------

    projects = relationship(
        "Project",
        back_populates="user",
        cascade="all, delete-orphan"
    )


# =========================================================
# PROJECT
# =========================================================

class Project(Base):

    __tablename__ = "projects"

    # =====================================================
    # PRIMARY KEY
    # =====================================================

    id = Column(
        Integer,
        primary_key=True,
        index=True
    )

    # =====================================================
    # USER
    # =====================================================

    user_id = Column(
        Integer,
        ForeignKey("users.id"),
        nullable=False
    )

    # =====================================================
    # ORIGINAL PROJECT INFORMATION
    #
    # These fields contain information entered by the user.
    # AI generation must not overwrite these fields.
    # =====================================================

    project_name = Column(
        String(255),
        nullable=False
    )

    category = Column(
        String(100),
        nullable=True
    )

    business_objective = Column(
        Text,
        nullable=True
    )

    target_users = Column(
        Text,
        nullable=True
    )

    problem_statement = Column(
        Text,
        nullable=True
    )

    expected_features = Column(
        Text,
        nullable=True
    )

    technology_preferences = Column(
        Text,
        nullable=True
    )

    timeline = Column(
        String(255),
        nullable=True
    )

    additional_instructions = Column(
        Text,
        nullable=True
    )

    # =====================================================
    # AI GENERATED DESCRIPTION
    #
    # Generated by:
    # POST /ai/generate-description/{project_id}
    # =====================================================

    overview = Column(
        Text,
        nullable=True
    )

    ai_problem_statement = Column(
        Text,
        nullable=True
    )

    proposed_solution = Column(
        Text,
        nullable=True
    )

    target_audience = Column(
        Text,
        nullable=True
    )

    business_value = Column(
        Text,
        nullable=True
    )

    major_features = Column(
        Text,
        nullable=True
    )

    expected_outcome = Column(
        Text,
        nullable=True
    )

    # =====================================================
    # AI GENERATED PRD
    #
    # Generated by:
    # POST /ai/generate-prd/{project_id}
    # =====================================================

    product_overview = Column(
        Text,
        nullable=True
    )

    prd_problem_statement = Column(
        Text,
        nullable=True
    )

    goals_and_objectives = Column(
        Text,
        nullable=True
    )

    prd_target_users = Column(
        Text,
        nullable=True
    )

    functional_requirements = Column(
        Text,
        nullable=True
    )

    user_workflows = Column(
        Text,
        nullable=True
    )

    business_rules = Column(
        Text,
        nullable=True
    )

    non_functional_requirements = Column(
        Text,
        nullable=True
    )

    assumptions_and_dependencies = Column(
        Text,
        nullable=True
    )

    acceptance_criteria = Column(
        Text,
        nullable=True
    )

    # =====================================================
    # AI GENERATED SPRINT PLAN
    # =====================================================

    sprint_plan = Column(
        Text,
        nullable=True
    )

    # =====================================================
    # RELATIONSHIPS
    # =====================================================

    user = relationship(
        "User",
        back_populates="projects"
    )

    tasks = relationship(
        "Task",
        back_populates="project",
        cascade="all, delete-orphan"
    )


# =========================================================
# TASK
# =========================================================

class Task(Base):

    __tablename__ = "tasks"

    # =====================================================
    # PRIMARY KEY
    # =====================================================

    id = Column(
        Integer,
        primary_key=True,
        index=True
    )

    # =====================================================
    # PROJECT
    # =====================================================

    project_id = Column(
        Integer,
        ForeignKey("projects.id"),
        nullable=False
    )

    # =====================================================
    # TASK INFORMATION
    # =====================================================

    task_title = Column(
        String(255),
        nullable=False
    )

    description = Column(
        Text,
        nullable=True
    )

    task_type = Column(
        String(100),
        nullable=True
    )

    module = Column(
        String(150),
        nullable=True
    )

    priority = Column(
        String(50),
        nullable=True
    )

    acceptance_criteria = Column(
        Text,
        nullable=True
    )

    owner_role = Column(
        String(150),
        nullable=True
    )

    dependencies = Column(
        Text,
        nullable=True
    )

    estimated_complexity = Column(
        String(100),
        nullable=True
    )

    # =====================================================
    # TASK STATUS
    # =====================================================

    status = Column(
        String(50),
        default="Todo",
        nullable=False
    )

    # =====================================================
    # TASK SOURCE
    #
    # manual = manually created
    # ai     = AI generated
    # =====================================================

    source = Column(
        String(50),
        default="manual",
        nullable=False
    )

    # =====================================================
    # RELATIONSHIP
    # =====================================================

    project = relationship(
        "Project",
        back_populates="tasks"
    )